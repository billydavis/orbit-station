"""Writes src/core/BuildStamp.cpp with the time of this build.

__DATE__/__TIME__ only change when the file using them is recompiled, so after
an incremental build they could show an older time than the firmware really
has. This runs before every build and rewrites one small file, so the stamp is
always current. The generated file is in .gitignore.
"""
import time
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)

stamp = time.strftime("%b %d %Y %H:%M:%S")
out = Path(env.subst("$PROJECT_DIR")) / "src" / "core" / "BuildStamp.cpp"  # noqa: F821
out.write_text(
    "// Generated by scripts/build_stamp.py before every build. Do not edit.\n"
    '#include "BuildStamp.h"\n'
    f'const char *const BUILD_STAMP = "{stamp}";\n',
    encoding="utf-8",
)
