"""Stamps each build and keeps what's needed to decode its crashes later.

Before every build this writes src/core/BuildStamp.cpp (gitignored) with:
- BUILD_STAMP: the build's real time. __DATE__/__TIME__ only change when the
  file using them is recompiled, so after an incremental build they could show
  an older time than the firmware really has.
- BUILD_COMMIT: the git commit it was built from, with "+dirty" when there
  were uncommitted changes.

After each build it saves a zip in builds/ (gitignored) named after the stamp,
environment and commit, holding the ELF and map (for decoding backtraces), the
firmware image, the commit's uncommitted changes and new files, and the
platform, toolchain and library versions. The newest KEEP builds are kept.
Skipped in CI.
"""
import hashlib
import json
import os
import re
import subprocess
import time
import zipfile
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)

KEEP = 20
SOURCE_DIRS = ("src", "lib", "include", "scripts", "assets", "fonts", "images")

project = Path(env.subst("$PROJECT_DIR"))  # noqa: F821


def git(*args):
    try:
        return subprocess.run(
            ["git", *args], cwd=project, capture_output=True, text=True, encoding="utf-8", check=True
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None


now = time.localtime()
stamp = time.strftime("%b %d %Y %H:%M:%S", now)
sha = (git("rev-parse", "--short=10", "HEAD") or "").strip() or "unknown"
dirty = bool((git("status", "--porcelain") or "").strip())
commit = sha + ("+dirty" if dirty else "")

out = project / "src" / "core" / "BuildStamp.cpp"
out.write_text(
    "// Generated by scripts/build_stamp.py before every build. Do not edit.\n"
    '#include "BuildStamp.h"\n'
    f'const char *const BUILD_STAMP = "{stamp}";\n'
    f'const char *const BUILD_COMMIT = "{commit}";\n',
    encoding="utf-8",
)


def versions():
    """Platform, toolchain and library versions this build used."""
    info = {}
    try:
        platform = env.PioPlatform()  # noqa: F821
        info["platform"] = f"{platform.name}@{platform.version}"
        packages = {}
        for name in platform.packages:
            try:
                version = platform.get_package_version(name)
            except Exception:  # noqa: BLE001 (not installed for this board)
                version = None
            if version:
                packages[name] = str(version)
        info["packages"] = packages
    except Exception as e:  # noqa: BLE001
        info["platformError"] = str(e)
    libs = {}
    libdeps = project / ".pio" / "libdeps" / env.subst("$PIOENV")  # noqa: F821
    for d in sorted(libdeps.glob("*/")) if libdeps.exists() else []:
        manifest = d / "library.json"
        if manifest.exists():
            try:
                libs[d.name] = json.loads(manifest.read_text(encoding="utf-8")).get("version")
                continue
            except (ValueError, OSError):
                pass
        props = d / "library.properties"
        if props.exists():
            for line in props.read_text(encoding="utf-8", errors="replace").splitlines():
                if line.startswith("version="):
                    libs[d.name] = line.split("=", 1)[1].strip()
    info["libraries"] = libs
    return info


def archive(target, source, env):
    build = Path(env.subst("$BUILD_DIR"))
    prog = env.subst("$PROGNAME")
    folder = project / "builds"
    folder.mkdir(exist_ok=True)
    # Name it from the stamp that was compiled in: PlatformIO can load this
    # script more than once in a run, and the last load's stamp is the one used.
    compiled = dict(re.findall(r'(BUILD_\w+) = "([^"]*)"', out.read_text(encoding="utf-8")))
    built = compiled.get("BUILD_STAMP", stamp)
    built_commit = compiled.get("BUILD_COMMIT", commit)
    when = time.strftime("%Y%m%d-%H%M%S", time.strptime(built, "%b %d %Y %H:%M:%S"))
    name = f"{when}-{env.subst('$PIOENV')}-{built_commit.replace('+', '-')}.zip"
    elf = build / f"{prog}.elf"
    meta = {
        "built": built,
        "commit": built_commit,
        # The board reports the first 16 digits (firmwareElfSha, crash output).
        "elfSha256": hashlib.sha256(elf.read_bytes()).hexdigest() if elf.exists() else None,
        "environment": env.subst("$PIOENV"),
        **versions(),
    }
    with zipfile.ZipFile(folder / name, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for ext in ("elf", "map", "bin"):
            f = build / f"{prog}.{ext}"
            if f.exists():
                z.write(f, f.name)
        z.writestr("build.json", json.dumps(meta, indent=2))
        if dirty:
            z.writestr("uncommitted.diff", git("diff", "HEAD", "--binary") or "")
            for rel in (git("ls-files", "--others", "--exclude-standard") or "").splitlines():
                if rel.split("/", 1)[0] in SOURCE_DIRS or rel == "platformio.ini":
                    z.write(project / rel, "untracked/" + rel)
    zips = sorted(folder.glob("*.zip"), key=lambda p: p.stat().st_mtime, reverse=True)
    for old in zips[KEEP:]:
        old.unlink()
    print(f"Build kept as builds/{name}")


if not os.environ.get("CI"):
    env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", archive)  # noqa: F821
